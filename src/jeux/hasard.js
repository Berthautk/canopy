// Hasard reproductible (même graine = même tirage) : le « Quiz du jour » est le même toute la journée.
export function generateur(graine) {
  let s = 0; for (const c of String(graine)) s = (s * 31 + c.charCodeAt(0)) >>> 0;
  return () => { s = (s + 0x6d2b79f5) >>> 0; let t = s; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}
export function melanger(liste, alea = Math.random) {
  const l = [...liste]; for (let i = l.length - 1; i > 0; i--) { const j = Math.floor(alea() * (i + 1)); [l[i], l[j]] = [l[j], l[i]]; } return l;
}
